export function byClassification(c: FeatureAuditRecord['classification']): FeatureAuditRecord[] {
  return FEATURE_AUDIT_RECORDS.filter((r) => r.classification === c);
}

export function byPriority(p: FeatureAuditRecord['priority']): FeatureAuditRecord[] {
  return FEATURE_AUDIT_RECORDS.filter((r) => r.priority === p);
}

export function governanceViolations(): FeatureAuditRecord[] {
  return FEATURE_AUDIT_RECORDS.filter((r) => r.governanceStatus === 'VIOLATION');
}

export function classificationCounts(): Record<FeatureAuditRecord['classification'], number> {
  const counts = { KEEP: 0, MODIFY: 0, MERGE: 0, REMOVE: 0, MISSING: 0, BROKEN: 0 };
  for (const r of FEATURE_AUDIT_RECORDS) counts[r.classification] += 1;
  return counts;
}
